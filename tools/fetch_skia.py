#!/usr/bin/env python3
"""Resolve and download matching Skia release binaries with curl, never build Skia."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import zipfile


REPOSITORY = "HumbleUI/SkiaBuild"
REQUIRED_LIBRARIES = ("skia", "svg", "skshaper", "skunicode_core", "skunicode_icu")


def curl(url, destination, *, api=False):
    executable = shutil.which("curl.exe") or shutil.which("curl")
    if not executable:
        raise RuntimeError("curl is required to download Skia release binaries")
    command = [executable,
               "--fail", "--location", "--retry", "4", "--retry-delay", "2",
               "--silent", "--show-error", "--output", str(destination)]
    if api:
        command += ["--header", "Accept: application/vnd.github+json"]
        token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
        if token:
            command += ["--header", f"Authorization: Bearer {token}"]
    try:
        subprocess.run(command + [url], check=True)
    except subprocess.CalledProcessError as error:
        # The command may contain an API token; do not include it in a traceback.
        raise RuntimeError(f"curl could not download {url} (exit {error.returncode})") from None


def resolve(platform, arch, version):
    endpoint = "latest" if version == "latest" else "tags/" + version
    with tempfile.TemporaryDirectory() as temporary:
        metadata = Path(temporary) / "release.json"
        curl(f"https://api.github.com/repos/{REPOSITORY}/releases/{endpoint}", metadata, api=True)
        release = json.loads(metadata.read_text(encoding="utf-8"))
    tag = release["tag_name"]
    filename = f"Skia-{tag}-{platform}-Release-{arch}.zip"
    assets = [asset for asset in release["assets"] if asset["name"] == filename]
    if len(assets) != 1:
        raise RuntimeError(f"{REPOSITORY} {tag} has no unique {filename}; refusing a source build")
    asset = assets[0]
    digest = asset.get("digest", "")
    if not re.fullmatch(r"sha256:[0-9a-f]{64}", digest):
        raise RuntimeError(f"{filename} has no SHA-256 release digest")
    return {"tag": tag, "platform": platform, "arch": arch,
            "url": asset["browser_download_url"], "digest": digest, "asset": filename}


def configure(root, metadata):
    output = root / "out" / f"Release-{metadata['arch']}"
    prefix, suffix = ("", ".lib") if metadata["platform"] == "windows" else ("lib", ".a")
    for name in REQUIRED_LIBRARIES:
        library = output / f"{prefix}{name}{suffix}"
        if not library.is_file():
            raise RuntimeError(f"Incomplete Skia prebuilt: {library}")
    for header in ("include/core/SkCanvas.h", "modules/svg/include/SkSVGDOM.h",
                   "src/gpu/vk/vulkanmemoryallocator/VulkanMemoryAllocatorPriv.h"):
        if not (root / header).is_file():
            raise RuntimeError(f"Missing Skia prebuilt header: {header}")
    definitions = (output / "defines.cmake").read_text(encoding="utf-8")
    if "-DSK_VULKAN" not in definitions or "-DSK_GANESH" not in definitions:
        raise RuntimeError("The Skia prebuilt does not enable the required Ganesh/Vulkan backend")
    # Only public Skia feature definitions belong in consumers. The producer's
    # defines.cmake also contains private codec and third-party implementation flags.
    features = sorted(set(re.findall(r"-D(SK_[A-Z0-9_]+)(?=\s|\)|$)", definitions)))
    features = [feature for feature in features
                if not feature.endswith("_IMPLEMENTATION") and feature != "SK_USE_INTERNAL_VULKAN_HEADERS"]
    settings = {
        "KINE_SKIA_DIR": root.as_posix(),
        "KINE_SKIA_INCLUDE_DIR": root.as_posix(),
        "KINE_SKIA_LIBRARY": (output / f"{prefix}skia{suffix}").as_posix(),
        "KINE_SKIA_BUILD_NAME": f"Release-{metadata['arch']}",
        "KINE_SKIA_PREBUILT_DEFINITIONS": ";".join(features),
        "KINE_SKIA_PREBUILT": "ON",
        "KINE_SKIA_AUTO_DOWNLOAD": "OFF",
    }
    for name, variable in (("svg", "SVG"), ("skshaper", "SKSHAPER"),
                           ("skunicode_core", "SKUNICODE_CORE"), ("skunicode_icu", "SKUNICODE_ICU")):
        settings[f"KINE_SKIA_{variable}_LIBRARY"] = (output / f"{prefix}{name}{suffix}").as_posix()
    (root / "skia.cmake").write_text(
        "# Generated by tools/fetch_skia.py; headers and binaries come from the same release.\n" +
        "".join(f'set({key} "{value}" CACHE STRING "" FORCE)\n' for key, value in settings.items()),
        encoding="utf-8")
    return output


def download(root, metadata):
    root = root.resolve()
    marker = root / "release.json"
    if marker.is_file() and json.loads(marker.read_text(encoding="utf-8")) == metadata:
        configure(root, metadata)
        print(f"Using cached Skia {metadata['tag']} ({metadata['platform']}/{metadata['arch']})")
        return
    root.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=root.parent) as temporary:
        archive = Path(temporary) / "skia.zip"
        staging = Path(temporary) / "package"
        staging.mkdir()
        curl(metadata["url"], archive)
        with archive.open("rb") as stream:
            digest = "sha256:" + hashlib.file_digest(stream, "sha256").hexdigest()
        if digest != metadata["digest"]:
            raise RuntimeError("Skia release checksum does not match GitHub's SHA-256 digest")
        with zipfile.ZipFile(archive) as package:
            for item in package.infolist():
                target = (staging / item.filename).resolve()
                if not target.is_relative_to(staging):
                    raise RuntimeError(f"Invalid archive entry: {item.filename}")
            package.extractall(staging)
        configure(staging, metadata)
        if root.exists():
            # Both targets are resolved children of this download's cache
            # directory; never recursively remove a computed external path.
            previous = Path(temporary) / "previous"
            if root == root.parent or not previous.resolve().is_relative_to(root.parent):
                raise RuntimeError("Skia cache replacement escaped its parent directory")
            root.rename(previous)
        staging.rename(root)
    configure(root, metadata)
    marker.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(f"Downloaded Skia {metadata['tag']} ({metadata['platform']}/{metadata['arch']})")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--platform", choices=("windows", "linux", "macos", "android"), required=True)
    parser.add_argument("--arch", choices=("x64", "arm64"), required=True)
    parser.add_argument("--version", default="latest")
    parser.add_argument("--resolve-only", action="store_true")
    parser.add_argument("--metadata", type=Path)
    args = parser.parse_args()
    repo = Path(__file__).resolve().parent.parent
    root = repo / ".cache" / "skia" / f"{args.platform}-{args.arch}"
    metadata_file = args.metadata or root.parent / f"{args.platform}-{args.arch}-release.json"
    if args.resolve_only or not metadata_file.is_file():
        metadata = resolve(args.platform, args.arch, args.version)
        metadata_file.parent.mkdir(parents=True, exist_ok=True)
        metadata_file.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    else:
        metadata = json.loads(metadata_file.read_text(encoding="utf-8"))
        if (metadata["platform"], metadata["arch"]) != (args.platform, args.arch):
            raise RuntimeError("Skia release metadata does not match the requested target")
    if not args.resolve_only:
        download(root, metadata)
    outputs = {"version": metadata["tag"], "path": root.as_posix(),
               "cmake": (root / "skia.cmake").as_posix(),
               "library": (root / "out" / f"Release-{args.arch}" /
                           ("skia.lib" if args.platform == "windows" else "libskia.a")).as_posix(),
               "cache-key": f"skia-{args.platform}-{args.arch}-{metadata['digest'][7:]}"}
    output_file = os.environ.get("GITHUB_OUTPUT")
    if output_file:
        with open(output_file, "a", encoding="utf-8") as stream:
            for key, value in outputs.items():
                stream.write(f"{key}={value}\n")
    print(json.dumps(outputs))


if __name__ == "__main__":
    main()
