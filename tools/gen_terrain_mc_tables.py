#!/usr/bin/env python3
"""Generate the GPU terrain mesher shader from the Odin marching-cubes table.

The GPU mesher must use exactly the same triangle table as the CPU mesher, so
we derive it mechanically from src/engine/util/marching_cubes/cubes.odin instead
of transcribing 4096 integers by hand.

The table is inlined (rather than #included) because glslc's include
preprocessor rewrites `int[4096](...)` to `int[4096] (...)` and glslang then
fails to parse the 4096-element constructor.

Edit vendor/kine_vulkan_compositor/src/kine_terrain_mc.comp.in, then run:
    python tools/gen_terrain_mc_tables.py
which writes vendor/kine_vulkan_compositor/src/kine_terrain_mc.comp.
"""

from __future__ import annotations

import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
ODIN = REPO / "src" / "engine" / "util" / "marching_cubes" / "cubes.odin"
TEMPLATE = REPO / "vendor" / "kine_vulkan_compositor" / "src" / "kine_terrain_mc.comp.in"
OUT = REPO / "vendor" / "kine_vulkan_compositor" / "src" / "kine_terrain_mc.comp"
TABLES = REPO / "vendor" / "kine_vulkan_compositor" / "src" / "kine_terrain_mc_tables.glsl"

MARKER = "//@MC_TRI_TABLE@"
EXPECTED = 256 * 16


def extract_tri_table(text: str) -> list[int]:
    start = text.index("MC_Tri_Table")
    brace = text.index("{", start)
    depth = 0
    end = brace
    for i in range(brace, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                end = i
                break
    body = text[brace + 1 : end]
    return [int(v) for v in re.findall(r"-?\d+", body)]


def build_table_glsl(values: list[int]) -> str:
    lines = [
        "// Generated by tools/gen_terrain_mc_tables.py from",
        "// src/engine/util/marching_cubes/cubes.odin (MC_Tri_Table).",
        "// Do not edit by hand; regenerate instead.",
        "const int MC_TRI[%d] = int[%d](" % (EXPECTED, EXPECTED),
    ]
    rows = []
    for i in range(0, EXPECTED, 16):
        chunk = values[i : i + 16]
        rows.append("    " + ", ".join(str(v) for v in chunk))
    # GLSL array constructors reject a trailing comma, so join rows with commas
    # between them rather than appending one to every row.
    lines.append(",\n".join(rows))
    lines.append(");")
    return "\n".join(lines)


def main() -> int:
    values = extract_tri_table(ODIN.read_text(encoding="utf-8"))
    if len(values) != EXPECTED:
        print(
            f"error: expected {EXPECTED} table entries, parsed {len(values)}",
            file=sys.stderr,
        )
        return 1

    template = TEMPLATE.read_text(encoding="utf-8")
    if MARKER not in template:
        print(f"error: marker {MARKER} missing from {TEMPLATE}", file=sys.stderr)
        return 1

    OUT.write_text(template.replace(MARKER, build_table_glsl(values)), encoding="utf-8")
    if TABLES.exists():
        TABLES.unlink()
    print(f"wrote {OUT} ({EXPECTED} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
